import java.util.*;
public class Solution {
    public static void main(String[] args) {
        if (args.length != 1) {
            System.out.println("Provide a single argument.");
            System.exit(0);
        }
        String input = args[0];
        System.out.println(input);
        input = input.trim();
        System.out.println(input);
        System.exit(0);
    }   
}